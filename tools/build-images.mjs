#!/usr/bin/env node
/* ============================================================
   Avora Brands: responsive image builder (run only when images change)

   Reads the originals in images/ and writes:
     images/opt/<name>-<width>.webp   resized copies the pages actually load
     assets/js/images.js              width/height list used to build srcset

   Needs: cwebp (brew install webp) and macOS sips.
   Usage: node tools/build-images.mjs          only new or changed files
          node tools/build-images.mjs --force  rebuild everything
   ============================================================ */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = path.join(root, 'images'), out = path.join(src, 'opt');
const force = process.argv.includes('--force');
const WIDTHS = [480, 960, 1600];
const SKIP = /^(favicon|logo\.png|tool-)/;

/* only build images that a page, data file or stylesheet refers to */
const text = [...fs.readdirSync(root).filter(f => f.endsWith('.html')).map(f => path.join(root, f)),
  ...['js', 'css'].flatMap(d => fs.readdirSync(path.join(root, 'assets', d)).map(f => path.join(root, 'assets', d, f)))]
  .filter(f => !f.endsWith('/images.js')).map(f => fs.readFileSync(f, 'utf8')).join('\n');
const used = f => text.includes(f) || /^book-/.test(f) || new RegExp('opt/' + f.replace(/\.\w+$/, '').replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '-\\d+\\.webp').test(text);

fs.mkdirSync(out, { recursive: true });
const manifest = {};
let built = 0, bytesIn = 0, bytesOut = 0;
for (const f of fs.readdirSync(src).filter(f => /\.(jpe?g|png|webp)$/i.test(f) && !SKIP.test(f)).sort()) {
  if (!used(f)) continue;
  const file = path.join(src, f), base = f.replace(/\.\w+$/, '');
  const info = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' });
  const w = +info.match(/pixelWidth: (\d+)/)[1], h = +info.match(/pixelHeight: (\d+)/)[1];
  /* every step below the native width, plus the native width itself */
  const widths = [...WIDTHS.filter(x => x < w * .92), Math.min(w, 1600)];
  manifest[f] = [w, h, widths];
  bytesIn += fs.statSync(file).size;
  for (const x of widths) {
    const to = path.join(out, `${base}-${x}.webp`);
    if (force || !fs.existsSync(to) || fs.statSync(to).mtimeMs < fs.statSync(file).mtimeMs) {
      execFileSync('cwebp', ['-quiet', '-mt', '-m', '6', '-q', x > 1000 ? '74' : '78', '-resize', String(x), '0', file, '-o', to]);
      built++;
    }
    bytesOut += fs.statSync(to).size;
  }
}
fs.writeFileSync(path.join(root, 'assets/js/images.js'),
  '/* Generated by tools/build-images.mjs. Format: file: [width, height, [built widths]] */\nwindow.IMAGES = ' +
  JSON.stringify(manifest).replace(/\],"/g, '],\n"') + ';\n');
console.log(`${Object.keys(manifest).length} images, ${built} files written, originals ${(bytesIn / 1e6).toFixed(1)} MB, webp ${(bytesOut / 1e6).toFixed(1)} MB`);
